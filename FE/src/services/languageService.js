    if (m) return `${m[1]} mẫu Train`
    m = text.match(/^(\d+) samples$/)
    if (m) return `${m[1]} mẫu`
    m = text.match(/^(\d+) trees · Max depth (.+)$/)
    if (m) return `${m[1]} cây · Độ sâu tối đa ${translateCore(m[2], 'vi')}`
