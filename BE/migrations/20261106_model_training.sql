-- Additive migration: legacy experiment tables and endpoints remain unchanged.
BEGIN;
CREATE TABLE IF NOT EXISTS model_training_splits (
    id UUID PRIMARY KEY,
    dataset_version_id UUID NOT NULL REFERENCES dataset_versions(id),
    fingerprint VARCHAR(64) NOT NULL UNIQUE,
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_model_training_splits_dataset_version_id ON model_training_splits(dataset_version_id);
CREATE TABLE IF NOT EXISTS model_training_experiments (
    id UUID PRIMARY KEY,
    number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
    name VARCHAR(64) GENERATED ALWAYS AS
        ('Ex-' || lpad(number::text, greatest(3, length(number::text)), '0')) STORED UNIQUE NOT NULL,
    split_id UUID NOT NULL REFERENCES model_training_splits(id),
    created_by UUID REFERENCES users(id) ON DELETE SET NULL,
    configuration JSONB NOT NULL,
    evaluation JSONB NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    training_time_sec DOUBLE PRECISION,
    prediction_time_sec DOUBLE PRECISION,
    execution_time_sec DOUBLE PRECISION,
    performance_by_horizon JSONB NOT NULL DEFAULT '{}',
    prediction_rows JSONB NOT NULL DEFAULT '[]',
    library_versions JSONB NOT NULL DEFAULT '{}',
    logs JSONB NOT NULL DEFAULT '[]',
    error VARCHAR(512),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_training_status CHECK (status IN ('PENDING','RUNNING','COMPLETED','FAILED'))
);
CREATE INDEX IF NOT EXISTS ix_model_training_experiments_split_id ON model_training_experiments(split_id);
COMMIT;
